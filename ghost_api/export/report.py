"""Write report.md for a run (FR-47, FR-48), from the database only.

Sections: summary and usage, endpoints (status, confidence, samples), hypotheses with
evidence, the agent's reasoning log, known issues, and lessons for next time.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from ghost_api import __version__
from ghost_api.analysis.models import Endpoint
from ghost_api.export.confidence import confidence
from ghost_api.generator.spec import ClientSpec
from ghost_api.memory.store import RunRow, Store
from ghost_api.site import site_host

RESULT_MARK = {"confirmed": "confirmed", "rejected": "rejected", "inconclusive": "inconclusive"}


def build_report(store: Store, domain: str, run_id: int, spec: ClientSpec | None = None) -> str:
    run = store.get_run(run_id)
    if run is None:
        raise ValueError(f"run {run_id} not found")
    endpoints = store.load_endpoints(domain, store.latest_endpoint_run(domain))
    hypotheses = store.hypotheses_for_run(run_id)
    steps = store.steps_for_run(run_id)
    lessons = store.lessons_for(domain, limit=10)

    out: list[str] = [
        f"# Ghost API report: {domain}",
        "",
        f"Generated by Ghost API {__version__} for run #{run.id}. Goal: _{_md(run.goal)}_",
        "",
        "## Summary",
        "",
        *_summary(run, endpoints, spec),
        "",
        "## Endpoints",
        "",
    ]
    out += _endpoint_table(endpoints, domain) if endpoints else ["No endpoints were found."]
    out += ["", "## Hypotheses tested", ""]
    out += _hypotheses(hypotheses) or ["No direct-call tests in this run."]
    out += ["", "## How the agent explored", ""]
    out += _steps(steps) or ["The agent was not used in this run."]
    out += ["", "## Known issues", ""]
    out += _issues(endpoints, hypotheses, spec) or ["None found."]
    if lessons:
        out += ["", "## Lessons remembered for next time", ""]
        out += [f"- {_md(lesson)}" for lesson in lessons]
    out += ["", "---", "", _CONFIDENCE_NOTE, ""]
    return "\n".join(out)


_CONFIDENCE_NOTE = (
    "_Confidence: verified by live tests +2, callable directly +1, pagination confirmed +1, "
    "2-4 samples +1 or 5+ samples +2, failed -3. High is 4 or more, Medium 2-3, Low below 2._"
)


def _summary(run: RunRow, endpoints: list[Endpoint], spec: ClientSpec | None) -> list[str]:
    counts = {
        s: sum(e.status == s for e in endpoints) for s in ("verified", "unverified", "failed")
    }
    outcome = run.status
    if run.status == "running" and run.finished_at is None:
        outcome = "did not finish (stopped unexpectedly)"
    lines = [
        f"- **Outcome:** {outcome}",
        f"- **Endpoints:** {len(endpoints)} ({counts['verified']} verified, "
        f"{counts['unverified']} unverified, {counts['failed']} failed)",
    ]
    if spec is not None:
        methods = ", ".join(f"`{m.name}()`" for m in spec.methods)
        lines.append(f"- **Client:** `{spec.class_name}` with {methods}")
    duration = _duration(run.started_at, run.finished_at)
    lines.append(
        f"- **Usage:** {run.llm_calls} LLM call{_s(run.llm_calls)}, {run.tokens:,} tokens, "
        f"{run.request_count} captured request{_s(run.request_count)}"
        f"{', ' + duration if duration else ''}, $0.00 (free tiers)"
    )
    return lines


def _endpoint_table(endpoints: list[Endpoint], domain: str) -> list[str]:
    rows = [
        "| Endpoint | Status | Confidence | Samples | Auth | Paging | Notes |",
        "|---|---|---|---|---|---|---|",
    ]
    host = site_host(domain)
    for ep in endpoints:
        label = ep.label if ep.host == host else f"{ep.method} {ep.host}{ep.path_template}"
        paging = "-"
        if ep.pagination:
            mark = "" if ep.pagination.get("confirmed") else " (unconfirmed)"
            paging = f"{ep.pagination['style']}: `{ep.pagination['param']}`{mark}"
        rows.append(
            f"| `{_md(label)}` | {ep.status} | {confidence(ep)} | {ep.sample_count} | "
            f"{ep.auth_type or '-'} | {paging} | {_md(ep.status_note) or '-'} |"
        )
    return rows


def _hypotheses(hypotheses: list[dict[str, Any]]) -> list[str]:
    lines: list[str] = []
    current = None
    for h in hypotheses:
        if h["endpoint_key"] != current:
            current = h["endpoint_key"]
            if lines:
                lines.append("")
            lines += [f"**`{_md(str(current))}`**", ""]
        result = RESULT_MARK[str(h["result"])]
        lines.append(f"- {result}: {_md(str(h['text']))} ({_md(str(h['evidence']))})")
    return lines


def _steps(steps: list[dict[str, Any]]) -> list[str]:
    lines = []
    for s in steps:
        args = ", ".join(f"{k}={v!r}" for k, v in dict(s["args"]).items())
        lines.append(f"{s['step_no']}. `{s['action']}({_md(args)})`: {_md(str(s['thought']))}")
        lines.append(f"   - Result: {_md(str(s['result']))}")
    return lines


def _issues(
    endpoints: list[Endpoint], hypotheses: list[dict[str, Any]], spec: ClientSpec | None
) -> list[str]:
    issues = []
    for ep in endpoints:
        if ep.status in ("failed", "unverified"):
            issues.append(
                f"- `{_md(ep.label)}` is {ep.status}: {_md(ep.status_note) or 'not tested'}"
            )
        elif ep.status == "discovered":
            issues.append(
                f"- `{_md(ep.label)}` has not been verified yet "
                "(run `ghost-api verify` or `ghost-api refresh`)"
            )
        if ep.replayable is False:
            issues.append(f"- `{_md(ep.label)}` cannot be called outside the browser")
    for h in hypotheses:
        if h["result"] == "inconclusive":
            issues.append(f"- Inconclusive: {_md(str(h['text']))} ({_md(str(h['evidence']))})")
    if spec is not None:
        issues += [f"- Not in the client: {_md(s)}" for s in spec.skipped]
        for cred in spec.credentials:
            issues.append(f"- The client needs `{cred.arg}`: set `{cred.env}` or pass it in")
    return issues


def _duration(started: str, finished: str | None) -> str:
    if not finished:
        return ""
    try:
        seconds = (
            datetime.fromisoformat(finished) - datetime.fromisoformat(started)
        ).total_seconds()
    except ValueError:
        return ""
    return f"{seconds:.0f}s"


def _s(count: int) -> str:
    return "" if count == 1 else "s"


def _md(text: str) -> str:
    """Safe inside a Markdown table cell or list item."""
    return text.replace("|", "\\|").replace("\n", " ").strip()
