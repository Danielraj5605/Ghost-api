"""Turn a generated client into a package you can install, publish or vendor.

Next to the loose files (which you can copy into a project as they are), each generate
writes:

    package/python/       pyproject.toml, README.md, src/<module>/ (client, models, py.typed)
    package/typescript/   package.json, tsconfig.json, README.md, src/index.ts

`pip install output/<site>/package/python` and `npm install output/<site>/package/typescript`
then work, and `from <module> import <Client>` is the same import as with the loose files.
"""

from __future__ import annotations

import ast
import json
import shlex
from pathlib import Path
from typing import Any
from urllib.parse import urlencode

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from ghost_api import __version__
from ghost_api.generator.spec import ClientSpec, MethodSpec
from ghost_api.generator.ts_gen import camel

TEMPLATES = Path(__file__).parent / "templates"


def dist_name(module: str) -> str:
    return module.replace("_", "-")


def example_value(literal: str | None) -> Any:
    """'"dune"' -> 'dune', '12' -> 12: a generated test's example as a plain value."""
    if literal is None:
        return None
    try:
        return ast.literal_eval(literal)
    except (ValueError, SyntaxError):
        return literal


def curl_example(spec: ClientSpec, method: MethodSpec) -> str:
    """A copy-paste curl command for a method, using values seen while exploring."""
    base = f"https://{method.host}" if method.host else spec.base_url
    path = method.path
    for p in method.by_location("path"):
        path = path.replace("{" + p.name + "}", str(example_value(p.example) or f"<{p.name}>"))
    query = {
        p.wire: example_value(p.example)
        for p in method.by_location("query")
        if p.required and p.example is not None
    }
    creds = {c.arg: c for c in spec.credentials if c.arg in method.credentials}
    for cred in creds.values():
        if cred.location == "query":
            query[cred.wire] = f"${cred.env}"
    url = base + path + (f"?{urlencode(query, safe='$')}" if query else "")
    parts = ["curl"]
    if method.http_method != "GET":
        parts += ["-X", method.http_method]
    parts.append(shlex.quote(url) if "$" not in url else f'"{url}"')
    for name, value in method.headers.items():
        parts += ["-H", shlex.quote(f"{name}: {value}")]
    for cred in creds.values():
        if cred.location == "header":
            parts += ["-H", f'"{cred.wire}: ${cred.env}"']
    body = {
        p.wire: example_value(p.example)
        for p in method.by_location("body")
        if p.example is not None
    }
    if method.by_location("body"):
        parts += ["-H", shlex.quote("Content-Type: application/json")]
        parts += ["-d", shlex.quote(json.dumps(body))]
    return " ".join(parts)


def _env() -> Environment:
    env = Environment(
        loader=FileSystemLoader(TEMPLATES),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=StrictUndefined,
        autoescape=False,  # Markdown and config files
    )
    env.filters.update(camel=camel, json=json.dumps)
    return env


def readme(spec: ClientSpec, module: str, lang: str) -> str:
    methods = [
        {
            "method": m,
            "curl": curl_example(spec, m),
            "py_args": ", ".join(f"{p.name}={p.example}" for p in m.required if p.example),
            "ts_args": ", ".join(
                json.dumps(example_value(p.example)) for p in m.required if p.example
            ),
            "ts_name": camel(m.name),
            "ts_iter": "iter" + camel(m.name)[:1].upper() + camel(m.name)[1:],
        }
        for m in spec.methods
    ]
    return (
        _env()
        .get_template("package_readme.md.j2")
        .render(
            spec=spec,
            module=module,
            dist=dist_name(module),
            lang=lang,
            methods=methods,
            version=__version__,
            client_version=spec.version,
        )
    )


def python_package(spec: ClientSpec, module: str, files: dict[str, str], out_dir: Path) -> Path:
    """`files`: the rendered loose files ({module}.py, models.py, test_{module}.py)."""
    root = out_dir / "package" / "python"
    src = root / "src" / module
    src.mkdir(parents=True, exist_ok=True)
    (root / "tests").mkdir(exist_ok=True)
    clients = [spec.class_name, spec.async_class, spec.error_class, *spec.error_classes.values()]
    doc = f"{spec.class_name}: a typed client for {spec.domain} (generated by Ghost API)."
    lines = [f'"""{doc}"""', ""]
    lines += ["from .client import (", *(f"    {name}," for name in clients), ")"]
    if spec.model_names:
        lines += ["from .models import (", *(f"    {name}," for name in spec.model_names), ")"]
    lines += ["", f"__all__ = {[*clients, *spec.model_names]!r}", ""]
    init = "\n".join(lines)
    contents = {
        src / "__init__.py": init,
        src / "client.py": files[f"{module}.py"],
        src / "models.py": files["models.py"],
        src / "py.typed": "",
        root / "tests" / f"test_{module}.py": files[f"test_{module}.py"],
        root / "pyproject.toml": _env()
        .get_template("pyproject.toml.j2")
        .render(spec=spec, module=module, dist=dist_name(module), version=spec.version),
        root / "README.md": readme(spec, module, "python"),
    }
    if spec.changelog:
        contents[root / "CHANGELOG.md"] = spec.changelog
    for path, text in contents.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    return root


def typescript_package(spec: ClientSpec, module: str, client_source: str, out_dir: Path) -> Path:
    root = out_dir / "package" / "typescript"
    (root / "src").mkdir(parents=True, exist_ok=True)
    package_json = {
        "name": dist_name(module),
        "version": spec.version,
        "description": f"Unofficial typed client for {spec.domain} (generated by Ghost API)",
        "type": "module",
        "main": "./dist/index.js",
        "types": "./dist/index.d.ts",
        "exports": {".": {"types": "./dist/index.d.ts", "default": "./dist/index.js"}},
        "files": ["dist", "README.md"],
        "engines": {"node": ">=18"},
        "scripts": {"build": "tsc -p .", "prepare": "tsc -p ."},
        "devDependencies": {"typescript": "^5.4.0"},
        "keywords": [spec.domain, "api-client", "ghost-api"],
        "license": "UNLICENSED",
    }
    tsconfig = {
        "compilerOptions": {
            "target": "es2022",
            "module": "es2022",
            "moduleResolution": "bundler",
            "lib": ["es2022", "dom"],
            "strict": True,
            "declaration": True,
            "outDir": "dist",
            "rootDir": "src",
            "skipLibCheck": True,
        },
        "include": ["src"],
    }
    contents = {
        root / "src" / "index.ts": client_source,
        root / "package.json": json.dumps(package_json, indent=2) + "\n",
        root / "tsconfig.json": json.dumps(tsconfig, indent=2) + "\n",
        root / "README.md": readme(spec, module, "typescript"),
    }
    if spec.changelog:
        contents[root / "CHANGELOG.md"] = spec.changelog
    for path, text in contents.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    return root
