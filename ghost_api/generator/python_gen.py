"""Render a ClientSpec into Python files, then check them (Stage 6).

Output, in output/<domain>/:
    <name>_client.py   the client class
    models.py          pydantic models
    test_<name>.py     live tests (run in Stage 7)

Checks before anything is written:
    - every file compiles
    - no secret-looking value and no [REDACTED] placeholder is present (NFR-16)
"""

from __future__ import annotations

import re
import shutil
import subprocess
import sys
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jinja2 import Environment, FileSystemLoader, StrictUndefined

from ghost_api import __version__
from ghost_api.capture.filters import REDACTED, redact_text
from ghost_api.config import USER_AGENT_SUFFIX
from ghost_api.generator.naming import snake
from ghost_api.generator.spec import ClientSpec, CredentialSpec, MethodSpec

TEMPLATES = Path(__file__).parent / "templates"


class GenerationError(Exception):
    pass


@dataclass
class GeneratedClient:
    directory: Path
    module: str  # import name of the client module
    client_path: Path
    models_path: Path
    tests_path: Path
    formatted: bool


def module_name(spec: ClientSpec) -> str:
    return snake(spec.class_name.removesuffix("Client")) + "_client"


def render(spec: ClientSpec, packaged: bool = False) -> dict[str, str]:
    """Render all files to strings: {filename: source}. `packaged`: for package/python
    (the client imports its models only as `.models`)."""
    env = Environment(
        loader=FileSystemLoader(TEMPLATES),
        trim_blocks=True,
        lstrip_blocks=True,
        keep_trailing_newline=True,
        undefined=StrictUndefined,
        autoescape=False,  # generating Python, not HTML
    )
    env.filters["pyrepr"] = repr
    env.filters["doc"] = _doc
    env.filters["path_expr"] = _path_expr
    env.filters["creds"] = _creds
    env.filters["env_map"] = lambda creds: {c.arg: c.env for c in creds}

    module = module_name(spec)
    model_types = " ".join(f.type for m in spec.models for f in m.fields)
    context: dict[str, Any] = {
        "spec": spec,
        "module": module,
        "version": __version__,
        "generated_on": datetime.now(UTC).strftime("%Y-%m-%d"),
        "user_agent": f"{module}/{__version__} (generated by {USER_AGENT_SUFFIX})",
        "uses_any": bool(re.search(r"\bAny\b", model_types)),
        "uses_field": any(f.alias for m in spec.models for f in m.fields),
        "packaged": packaged,
    }
    return {
        f"{module}.py": env.get_template("client.py.j2").render(context),
        "models.py": env.get_template("models.py.j2").render(context),
        f"test_{module}.py": env.get_template("test_client.py.j2").render(context),
    }


def check(files: dict[str, str]) -> None:
    for name, source in files.items():
        try:
            compile(source, name, "exec")
        except SyntaxError as exc:
            raise GenerationError(f"{name} does not compile: {exc}") from exc
        if REDACTED in source:
            raise GenerationError(f"{name} contains a redacted placeholder")
        if redact_text(source) != source:
            raise GenerationError(f"{name} contains a value that looks like a secret")


def write(spec: ClientSpec, out_dir: Path) -> GeneratedClient:
    files = render(spec)
    check(files)
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, source in files.items():
        (out_dir / name).write_text(source, encoding="utf-8", newline="\n")
    formatted = _format(out_dir, list(files))
    if formatted:  # formatting must not break anything
        check({n: (out_dir / n).read_text(encoding="utf-8") for n in files})
    module = module_name(spec)
    from ghost_api.generator.package import python_package  # ts_gen imports this module

    packaged = render(spec, packaged=True)
    check(packaged)
    root = python_package(spec, module, packaged, out_dir)
    _format(root / "src" / module, ["client.py", "models.py"])
    return GeneratedClient(
        directory=out_dir,
        module=module,
        client_path=out_dir / f"{module}.py",
        models_path=out_dir / "models.py",
        tests_path=out_dir / f"test_{module}.py",
        formatted=formatted,
    )


def _format(directory: Path, names: list[str]) -> bool:
    """Format with ruff if it's installed; generated code is readable without it too."""
    cmd = [sys.executable, "-m", "ruff"] if _has_module("ruff") else None
    if cmd is None and shutil.which("ruff"):
        cmd = ["ruff"]
    if cmd is None:
        return False
    try:
        subprocess.run(
            [*cmd, "format", "--quiet", "--line-length", "100", *names],
            cwd=directory,
            check=True,
            capture_output=True,
            timeout=60,
        )
    except (subprocess.SubprocessError, OSError):
        return False
    return True


def _has_module(name: str) -> bool:
    import importlib.util

    return importlib.util.find_spec(name) is not None


# --- template filters ------------------------------------------------------------------------


def _doc(text: str) -> str:
    """Safe inside a triple-quoted docstring."""
    return text.replace("\\", "/").replace('"""', "'''").strip()


def _path_expr(method: MethodSpec) -> str:
    """'/api/books/{id}' -> f"/api/books/{quote(str(id), safe='')}"."""
    if "{" not in method.path:
        return repr(method.path)
    escaped = method.path.replace("'", "\\'")
    expr = re.sub(r"\{(\w+)\}", lambda m: "{quote(str(" + m.group(1) + "), safe='')}", escaped)
    return 'f"' + expr.replace('"', '\\"') + '"'


def _creds(method: MethodSpec, spec: ClientSpec, location: str) -> list[CredentialSpec]:
    wanted = set(method.credentials)
    return [c for c in spec.credentials if c.arg in wanted and location in ("any", c.location)]
