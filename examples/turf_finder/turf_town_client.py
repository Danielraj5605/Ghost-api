        if json is not None:
            json = {k: v for k, v in json.items() if v is not None}
        for attempt in range(self._max_retries + 1):
            wait = self._last_request + self._interval - time.monotonic()
            if wait > 0:
                time.sleep(wait)
            self._last_request = time.monotonic()
